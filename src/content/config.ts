import { defineCollection, z } from 'astro:content';

const projects = defineCollection({
  type: 'data',
  schema: z.object({
    slug: z.string(),
    order: z.number(),
    number: z.string(),
    title: z.string(),
    client: z.string(),
    year: z.string(),
    role: z.string(),
    summary: z.string(),
    description: z.string(),
    tools: z.array(z.string()).default([]),
    skills: z.array(z.string()).default([]),
    coverImage: z.string().optional().default(""),
    images: z.array(z.string()).default([]),
    link: z.string().optional(),
    linkLabel: z.string().optional(),
    caseStudyLink: z.string().optional(),
    password: z.string().optional(),
    topicCluster: z.string().optional(),
    relatedServices: z.array(z.string()).optional().default([]),
    limitations: z.string().optional(),
    publishedAt: z.string().optional(),
    updatedAt: z.string().optional(),
  }),
});

const photoImageSchema = z.object({
  id: z.string().optional(),
  src: z.string(),
  alt: z.string(),
  width: z.number().optional(),
  height: z.number().optional(),
  caption: z.string().optional(),
  title: z.string().optional(),
  story: z.string().optional(),
  capturedAt: z.string().optional(),
  capturedTimeZone: z.string().optional(),
  location: z.string().optional(),
  order: z.number().optional(),
  isCover: z.boolean().optional(),
  camera: z.string().optional(),
  lens: z.string().optional(),
  focalLength: z.string().optional(),
  aperture: z.string().optional(),
  shutterSpeed: z.string().optional(),
  iso: z.union([z.number(), z.string()]).optional(),
  latitude: z.union([z.number(), z.string()]).optional(),
  longitude: z.union([z.number(), z.string()]).optional(),
  copyright: z.string().optional(),
  creator: z.string().optional(),
  credit: z.string().optional(),
  license: z.string().optional(),
});

const photoScoresSchema = z.object({
  scenery: z.number().min(1).max(10).optional(),
  food: z.number().min(1).max(10).optional(),
  cafe: z.number().min(1).max(10).optional(),
  relaxation: z.number().min(1).max(10).optional(),
  value: z.number().min(1).max(10).optional(),
  accessibility: z.number().min(1).max(10).optional(),
}).optional();

const sourceRefSchema = z.object({
  title: z.string(),
  url: z.string(),
  verifiedAt: z.string().optional(),
});

