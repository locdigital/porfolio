import fs from 'node:fs';
import path from 'node:path';

const rootDir = process.cwd();
const lineDir = path.join(rootDir, 'node_modules/majesticons/line');
const solidDir = path.join(rootDir, 'node_modules/majesticons/solid');
const outDir = path.join(rootDir, 'src/components/icons/majesticons');

if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

function cleanLineSvg(raw) {
  return raw
    .replace(/<svg[^>]*>/, '')
    .replace(/<\/svg>/, '')
    .replace(/stroke="black"/g, 'stroke="currentColor"')
    .replace(/\s*stroke-width="2"/g, '')
    .trim();
}

function cleanSolidSvg(raw) {
  return raw
    .replace(/<svg[^>]*>/, '')
    .replace(/<\/svg>/, '')
    .replace(/fill="black"/g, 'fill="currentColor"')
    .trim();
}

const icons = {};

if (fs.existsSync(lineDir)) {
  const lineFiles = fs.readdirSync(lineDir);
  for (const f of lineFiles) {
    if (!f.endsWith('.svg')) continue;
    const name = f.replace('-line.svg', '').replace('.svg', '');
    const raw = fs.readFileSync(path.join(lineDir, f), 'utf8');
    icons[name] = { line: cleanLineSvg(raw) };
  }
}

if (fs.existsSync(solidDir)) {
  const solidFiles = fs.readdirSync(solidDir);
  for (const f of solidFiles) {
    if (!f.endsWith('.svg')) continue;
    const name = f.replace('-solid.svg', '').replace('.svg', '');
    const raw = fs.readFileSync(path.join(solidDir, f), 'utf8');
    if (!icons[name]) icons[name] = {};
    icons[name].solid = cleanSolidSvg(raw);
  }
}

